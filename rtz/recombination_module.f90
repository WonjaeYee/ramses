  end if
  if (ios == 0) read(u, *, iostat=ios) nT_heIrr, lgT_heIrr_min, dlgT_heIrr
  if (ios == 0) then
     allocate(lga_heI_tot(nT_heIrr), lga_heI_gnd(nT_heIrr))
